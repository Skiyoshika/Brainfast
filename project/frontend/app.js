function parseCsv(text) {
  const lines = text.trim().split(/\r?\n/);
  const head  = lines.shift().split(',');
  return lines.map(line => { const cols = line.split(','); const obj = {}; head.forEach((h, i) => (obj[h] = cols[i] || '')); return obj; });
}

