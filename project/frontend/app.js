function t(key, vars) {
  const dict = currentLang === 'zh' ? LANGS.zh : LANGS.en;
  let str = dict[key];
  if (str === undefined) str = LANGS.en[key];
  if (str === undefined) str = key;
  if (vars) {
    Object.entries(vars).forEach(function(kv) {
      str = str.split('{' + kv[0] + '}').join(String(kv[1]));
    });
  }
  return str;
}

